/* ---------------------------------------------------------------------
   1. CRIAÇÃO DAS TABELAS (DDL)
   --------------------------------------------------------------------- */

CREATE TABLE Clientes (
    IdCliente       INT IDENTITY(1,1) CONSTRAINT PK_Clientes PRIMARY KEY,
    Nome            VARCHAR(100) NOT NULL,      -- digitado no balcão: alguns têm espaços sobrando
    CPF             CHAR(11)     NOT NULL CONSTRAINT UQ_Clientes_CPF UNIQUE,  -- só os números
    Email           VARCHAR(100) NULL,          -- alguns não informaram
    Telefone        VARCHAR(11)  NULL,          -- DDD + número, só os números
    DataNascimento  DATE         NOT NULL,
    Cidade          VARCHAR(50)  NOT NULL,
    UF              CHAR(2)      NOT NULL,
    DataCadastro    DATE         NOT NULL CONSTRAINT DF_Clientes_DataCadastro DEFAULT GETDATE()
);

CREATE TABLE Categorias (
    IdCategoria     INT IDENTITY(1,1) CONSTRAINT PK_Categorias PRIMARY KEY,
    NomeCategoria   VARCHAR(30)   NOT NULL CONSTRAINT UQ_Categorias_Nome UNIQUE,
    ValorDiaria     DECIMAL(10,2) NOT NULL,     -- diária ATUAL (reajustada em 01/09/2026)
    Descricao       VARCHAR(100)  NULL
);

CREATE TABLE Veiculos (
    IdVeiculo       INT IDENTITY(1,1) CONSTRAINT PK_Veiculos PRIMARY KEY,
    Placa           CHAR(7)      NOT NULL CONSTRAINT UQ_Veiculos_Placa UNIQUE,  -- padrão Mercosul, sem hífen
    Marca           VARCHAR(30)  NOT NULL,
    Modelo          VARCHAR(30)  NOT NULL,
    AnoFabricacao   SMALLINT     NOT NULL,
    Cor             VARCHAR(20)  NOT NULL,
    IdCategoria     INT          NOT NULL CONSTRAINT FK_Veiculos_Categorias REFERENCES Categorias (IdCategoria),
    Quilometragem   INT          NOT NULL,
    Status          VARCHAR(20)  NOT NULL CONSTRAINT DF_Veiculos_Status DEFAULT 'Disponível'
                    CONSTRAINT CK_Veiculos_Status CHECK (Status IN ('Disponível', 'Alugado', 'Manutenção'))
);

CREATE TABLE Locacoes (
    IdLocacao              INT IDENTITY(1,1) CONSTRAINT PK_Locacoes PRIMARY KEY,
    IdCliente              INT           NOT NULL CONSTRAINT FK_Locacoes_Clientes REFERENCES Clientes (IdCliente),
    IdVeiculo              INT           NOT NULL CONSTRAINT FK_Locacoes_Veiculos REFERENCES Veiculos (IdVeiculo),
    DataRetirada           DATE          NOT NULL,
    DataPrevistaDevolucao  DATE          NOT NULL,
    DataDevolucao          DATE          NULL,     -- NULL = carro ainda com o cliente, ou locação cancelada
    ValorDiaria            DECIMAL(10,2) NOT NULL, -- diária cobrada NO DIA da retirada
    KmRetirada             INT           NOT NULL,
    KmDevolucao            INT           NULL,
    Status                 VARCHAR(20)   NOT NULL
                           CONSTRAINT CK_Locacoes_Status CHECK (Status IN ('Em andamento', 'Finalizada', 'Cancelada')),
    CONSTRAINT CK_Locacoes_Datas CHECK (DataPrevistaDevolucao > DataRetirada)
);

CREATE TABLE Pagamentos (
    IdPagamento     INT IDENTITY(1,1) CONSTRAINT PK_Pagamentos PRIMARY KEY,
    IdLocacao       INT           NOT NULL CONSTRAINT FK_Pagamentos_Locacoes REFERENCES Locacoes (IdLocacao),
    DataPagamento   DATE          NOT NULL,
    Valor           DECIMAL(10,2) NOT NULL CONSTRAINT CK_Pagamentos_Valor CHECK (Valor > 0),
    FormaPagamento  VARCHAR(20)   NOT NULL
);

CREATE TABLE Manutencoes (
    IdManutencao    INT IDENTITY(1,1) CONSTRAINT PK_Manutencoes PRIMARY KEY,
    IdVeiculo       INT           NOT NULL CONSTRAINT FK_Manutencoes_Veiculos REFERENCES Veiculos (IdVeiculo),
    DataEntrada     DATE          NOT NULL,
    DataSaida       DATE          NULL,     -- NULL = carro ainda na oficina
    Tipo            VARCHAR(20)   NOT NULL CONSTRAINT CK_Manutencoes_Tipo CHECK (Tipo IN ('Preventiva', 'Corretiva')),
    Descricao       VARCHAR(100)  NOT NULL,
    Custo           DECIMAL(10,2) NULL      -- NULL enquanto o serviço não termina
);
GO

